# Arrays em dimensões
import numpy as np

# Criando um array 1D
array_1d = np.array([1, 2, 3, 4, 5])
print("Array 1D:")
print(array_1d)

# Criando um array 2D
print()
array_2d = np.array([[1, 2, 3], [4, 5, 6]])
print("Array 2D:")
print(array_2d)

# Criando um array 3D
print()
array_3d = np.array([[[1, 2], [3, 4]], [[5, 6], [7, 8]]])
print("Array 3D:")
print(array_3d)
